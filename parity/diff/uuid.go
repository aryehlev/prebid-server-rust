package diff

import (
	"regexp"
	"strconv"
	"strings"

	"github.com/prebid/prebid-server/v4/parity"
)

// UUID placeholders (uuid_placeholder rules). Go fills some values with
// random v4 UUIDs, so no exact comparison is possible there. Each side gets
// its own numbering:
//
//  1. collect: UUIDs found at a rule's target positions are "generated". For
//     request_id_uuid, tid_uuid and generated_bid_id the value must be a v4
//     UUID (Go uses uuid.NewV4) that the caller did not supply anywhere in the
//     case input, which is exactly when Go generates it (input id {{UUID}},
//     absent tid, generate_request_id). cache_uuid takes any UUID the cache
//     answered with.
//  2. every occurrence of a generated UUID, at the target or anywhere it is
//     referenced (event URLs, targeting, cache URLs), becomes <uuid#n>, with n
//     assigned by first appearance in a canonical traversal after sorting.
//
// Equal UUIDs therefore stay equal and distinct ones distinct: if Go uses one
// tid for two bidders and Rust two different ones, Go reads <uuid#1>,<uuid#1>
// and Rust <uuid#1>,<uuid#2>, which is a mismatch.

var (
	uuidAnywhere = regexp.MustCompile(`[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}`)
	uuidExact    = regexp.MustCompile(`^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$`)
)

// isUUIDv4 reports whether s is a canonical version-4, RFC 4122 variant UUID.
func isUUIDv4(s string) bool {
	return uuidExact.MatchString(s) && s[14] == '4' && strings.ContainsRune("89abAB", rune(s[19]))
}

// uuidSet collects and numbers the generated UUIDs of one side.
type uuidSet struct {
	rules *Rules
	// inputs is every caller-supplied text of the case (envelope, stored
	// data); a UUID found there was not generated by the server.
	inputs    string
	generated map[string]string // UUID -> rule ID
	numbers   map[string]int
}

func newUUIDSet(rules *Rules, inputs string) *uuidSet {
	return &uuidSet{rules: rules, inputs: inputs, generated: map[string]string{}, numbers: map[string]int{}}
}

// collect records n as generated by rule when it qualifies.
func (u *uuidSet) collect(rule string, stage parity.StageID, n *node) {
	if n == nil || n.kind != kindString || !u.rules.Active(rule, stage) {
		return
	}
	s := n.str
	if rule == RuleCacheUUID {
		if !uuidExact.MatchString(s) {
			return
		}
	} else if !isUUIDv4(s) || strings.Contains(u.inputs, s) {
		return
	}
	if _, seen := u.generated[s]; !seen {
		u.generated[s] = rule
	}
}

// collectAll records every node selected below the anchors.
func (u *uuidSet) collectAll(rule string, stage parity.StageID, root *node, anchors []string, selectors ...string) {
	for _, sel := range selectors {
		for _, n := range selectAll(root, anchors, sel) {
			u.collect(rule, stage, n)
		}
	}
}

// maskText replaces generated UUIDs with an unnumbered marker. Sort keys use
// it so both sides sort identically before numbering.
func (u *uuidSet) maskText(s string) string {
	if len(u.generated) == 0 {
		return s
	}
	return uuidAnywhere.ReplaceAllStringFunc(s, func(m string) string {
		if _, ok := u.generated[m]; ok {
			return "<uuid>"
		}
		return m
	})
}

// number replaces every generated UUID in s whose rule applies to stage with
// its placeholder, numbering new ones in order of appearance.
func (u *uuidSet) number(stage parity.StageID, s string) string {
	if len(u.generated) == 0 {
		return s
	}
	return uuidAnywhere.ReplaceAllStringFunc(s, func(m string) string {
		rule, ok := u.generated[m]
		if !ok || !u.rules.Active(rule, stage) {
			return m
		}
		n, ok := u.numbers[m]
		if !ok {
			n = len(u.numbers) + 1
			u.numbers[m] = n
		}
		return "<uuid#" + strconv.Itoa(n) + ">"
	})
}

// numberNode numbers every string in a tree, keeping the raw spelling in step.
func (u *uuidSet) numberNode(stage parity.StageID, root *node) {
	if len(u.generated) == 0 {
		return
	}
	walk(root, func(n *node) {
		if n.kind == kindString {
			n.str = u.number(stage, n.str)
			n.raw = u.number(stage, n.raw)
		}
	})
}

// numberHeaders numbers the values of a header list in place.
func (u *uuidSet) numberHeaders(stage parity.StageID, list parity.HeaderList) {
	for i := range list {
		list[i][1] = u.number(stage, list[i][1])
	}
}

// count returns how many UUIDs were collected.
func (u *uuidSet) count() int {
	return len(u.generated)
}
