//! The generated Rust module for one Go package.
//!
//! The output is already in rustfmt's canonical form for `rust/rustfmt.toml` (so `--check`
//! compares bytes without running rustfmt): imports grouped and sorted the way rustfmt sorts
//! them, attributes and items broken the way rustfmt breaks them when they exceed the width,
//! and docs from [`docs`].

use core::{iter::Peekable, str::Chars};
use std::{
    cmp::Ordering,
    collections::{BTreeMap, BTreeSet},
};

use super::{
    config::{Config, FieldNames, Override, PackageConfig},
    docs::{self, WIDTH},
    model::{Decl, DeclKind, Field, Package, TypeKind, TypeRef},
    names,
    registry::{Ctx, Registry, TypeInfo},
};
use crate::error::{Result, ToolError};

/// rustfmt's `attr_fn_like_width`: longer attribute arguments go one per line.
const ATTR_ARGS_WIDTH: usize = 70;

/// The first line of every generated file.
pub const GENERATED: &str = "// Code generated by pbs-devtools typegen. DO NOT EDIT.";

/// One generated package module, with what the indexes need to know about it.
#[derive(Debug, Clone)]
pub struct Generated {
    /// The Go import path.
    pub go_path: String,
    /// The Rust module path.
    pub module: String,
    /// The output file, relative to the crate directory.
    pub out: String,
    /// The file content.
    pub content: String,
    /// Every Go type the module ports (generated or hand-written).
    pub types: Vec<IndexType>,
    /// Every exported Go constant the module ports.
    pub consts: Vec<IndexConst>,
    /// Every exported Go function and method, with its hand-written port.
    pub funcs: Vec<IndexFunc>,
}

/// A ported Go type.
#[derive(Debug, Clone)]
pub struct IndexType {
    /// The Go type name (`BidRequest`).
    pub go: String,
    /// Go's `reflect.Type.String()` (`openrtb2.BidRequest`).
    pub go_name: String,
    /// The Rust path from the crate root (`openrtb2::BidRequest`).
    pub rust: String,
    /// Whether the Go type is a struct.
    pub is_struct: bool,
}

/// A ported Go constant.
#[derive(Debug, Clone)]
pub struct IndexConst {
    /// `pkg.Name` (`adcom1.PositionUnknown`).
    pub go_name: String,
    /// The Rust path from the crate root.
    pub rust: String,
}

/// A ported Go function or method.
#[derive(Debug, Clone)]
pub struct IndexFunc {
    /// `pkg.Name` or `pkg.Type.Method`.
    pub go_name: String,
    /// The Rust path from the crate root.
    pub rust: String,
    /// The Rust function pointer type.
    pub signature: String,
}

/// Generates the module for `pkg` as configured by `pc`.
///
/// # Errors
///
/// Fails on a Go declaration that cannot be generated and has no override, on a name collision,
/// on an override or function entry that matches nothing, and on a Go function or method with
/// no registered port.
pub fn package(
    reg: &Registry,
    config: &Config,
    pc: &PackageConfig,
    pkg: &Package,
) -> Result<Generated> {
    let mut e = Emitter::new(reg, config, pc, pkg);
    let mut output = Output::default();
    for decl in pkg.decls.iter().filter(|d| d.exported) {
        e.decl(decl, &mut output)?;
    }
    let stale: Vec<&String> = pc
        .overrides
        .keys()
        .filter(|k| !e.used.contains(k.as_str()))
        .collect();
    if !stale.is_empty() {
        return Err(ToolError::new(format!(
            "{}: overrides of {} match no exported declaration or field: {stale:?}",
            config.source, pc.go
        )));
    }
    let funcs = functions(config, pc, pkg, &output.go_funcs)?;
    if !output.items.is_empty() {
        let _ = e.ctx.uses.insert("pbs_gojson::GoJson".to_owned());
    }
    let mut lines = header(config, pkg);
    lines.push(String::new());
    lines.extend(imports(&e.ctx.uses));
    for item in output.items {
        lines.push(String::new());
        lines.extend(item);
    }
    let mut content = lines.join("\n");
    content.push('\n');
    Ok(Generated {
        go_path: pkg.path.clone(),
        module: pc.rust.clone(),
        out: pc.out.clone(),
        content,
        types: output.types,
        consts: output.consts,
        funcs,
    })
}

/// What the exported declarations of a package become.
#[derive(Default)]
struct Output {
    /// The generated items, in Go declaration order.
    items: Vec<Vec<String>>,
    /// The ported types.
    types: Vec<IndexType>,
    /// The ported constants.
    consts: Vec<IndexConst>,
    /// The Go functions and methods, keyed as [`func_key`] keys them.
    go_funcs: BTreeSet<String>,
}

/// The generated-file header.
fn header(config: &Config, pkg: &Package) -> Vec<String> {
    let module = if pkg.version.is_empty() {
        pkg.module.clone()
    } else {
        format!("{}@{}", pkg.module, pkg.version)
    };
    vec![
        GENERATED.to_owned(),
        "//".to_owned(),
        format!("// Source: {}", pkg.path),
        format!("// Module: {module}"),
        format!("// Config: {}", config.source),
        "//".to_owned(),
        "// Regenerate with `cargo run -p pbs-devtools -- typegen`; hand-written code for this"
            .to_owned(),
        "// package lives in the other files of its module.".to_owned(),
    ]
}

/// The hand-written ports of the package's Go functions and methods, which the config must
/// list exactly.
fn functions(
    config: &Config,
    pc: &PackageConfig,
    pkg: &Package,
    go_funcs: &BTreeSet<String>,
) -> Result<Vec<IndexFunc>> {
    let missing: Vec<&String> = go_funcs
        .iter()
        .filter(|f| !pc.functions.contains_key(*f))
        .collect();
    let extra: Vec<&String> = pc
        .functions
        .keys()
        .filter(|f| !go_funcs.contains(*f))
        .collect();
    if !missing.is_empty() || !extra.is_empty() {
        return Err(ToolError::new(format!(
            "{}: functions of {} are out of date: port and register {missing:?}; remove \
             {extra:?}",
            config.source, pc.go
        )));
    }
    Ok(pc
        .functions
        .iter()
        .map(|(go, port)| IndexFunc {
            go_name: format!("{}.{go}", pkg.name),
            rust: format!("{}::{}", pc.rust, port.rust),
            signature: port.signature.clone(),
        })
        .collect())
}

/// `Name` for a function, `Type.Name` for a method.
fn func_key(decl: &Decl) -> String {
    if decl.kind == DeclKind::Method {
        format!("{}.{}", decl.recv, decl.name)
    } else {
        decl.name.clone()
    }
}

struct Emitter<'a> {
    reg: &'a Registry,
    pc: &'a PackageConfig,
    pkg: &'a Package,
    ctx: Ctx<'a>,
    used: BTreeSet<String>,
    type_names: BTreeMap<String, String>,
    value_names: BTreeMap<String, String>,
}

impl<'a> Emitter<'a> {
    fn new(reg: &'a Registry, config: &'a Config, pc: &'a PackageConfig, pkg: &'a Package) -> Self {
        let aliases = pkg
            .decls
            .iter()
            .filter(|d| d.kind == DeclKind::Alias && d.exported)
            .filter(|d| !pc.overrides.get(&d.name).is_some_and(|o| o.skip))
            .filter_map(|d| {
                let target = d.ty.as_ref()?;
                let info = reg.get(&target.pkg, &target.name)?;
                Some((
                    format!("{}::{}::{}", info.crate_name, info.module, info.rust_name),
                    names::type_name(&d.name),
                ))
            })
            .collect();
        Self {
            reg,
            pc,
            pkg,
            ctx: Ctx {
                crate_name: &config.crate_name,
                module: &pc.rust,
                strings: pc.strings,
                uses: BTreeSet::new(),
                aliases,
            },
            used: BTreeSet::new(),
            type_names: BTreeMap::new(),
            value_names: BTreeMap::new(),
        }
    }

    /// Generates one exported declaration into `output`.
    fn decl(&mut self, decl: &Decl, output: &mut Output) -> Result<()> {
        let reg = self.reg;
        let o = self.take(&decl.name);
        let skip = o.is_some_and(|o| o.skip);
        match decl.kind {
            DeclKind::Struct | DeclKind::Named => {
                let info = reg.get(&self.pkg.path, &decl.name).ok_or_else(|| {
                    ToolError::new(format!("{}.{} is not registered", self.pkg.path, decl.name))
                })?;
                self.claim_type(&info.rust_name, &decl.name)?;
                if decl.kind == DeclKind::Named || decl.fields.is_empty() {
                    self.claim_value(&info.rust_name, &decl.name)?;
                }
                output.types.push(IndexType {
                    go: decl.name.clone(),
                    go_name: info.go_name.clone(),
                    rust: format!("{}::{}", self.pc.rust, info.rust_name),
                    is_struct: decl.kind == DeclKind::Struct,
                });
                if skip {
                    return Ok(());
                }
                if decl.generic {
                    return Err(self.error(decl, "is generic; skip it and write it by hand"));
                }
                let item = if decl.kind == DeclKind::Struct {
                    self.struct_item(decl, info)?
                } else {
                    self.named_item(decl, info)?
                };
                output.items.push(item);
            }
            DeclKind::Alias => {
                if !skip {
                    output.items.push(self.alias_item(decl)?);
                }
            }
            DeclKind::Interface => {
                if !skip {
                    return Err(self.error(decl, "is an interface; skip it and write it by hand"));
                }
            }
            DeclKind::Const if skip => {
                // Written by hand (for example a constant of a hand-written named string type,
                // which a generated `const` cannot construct): only its Rust name is claimed
                // and indexed.
                let name = o
                    .and_then(|o| o.rust_name.clone())
                    .unwrap_or_else(|| names::screaming(&decl.name));
                self.claim_value(&name, &decl.name)?;
                output.consts.push(IndexConst {
                    go_name: format!("{}.{}", self.pkg.name, decl.name),
                    rust: format!("{}::{name}", self.pc.rust),
                });
            }
            DeclKind::Const => {
                let (item, c) = self.const_item(decl, o)?;
                output.consts.push(c);
                output.items.push(item);
            }
            DeclKind::Func | DeclKind::Method => {
                let _ = output.go_funcs.insert(func_key(decl));
            }
        }
        Ok(())
    }

    /// The override for `key`, marking it used.
    fn take(&mut self, key: &str) -> Option<&'a Override> {
        let pc: &'a PackageConfig = self.pc;
        let o = pc.overrides.get(key)?;
        let _ = self.used.insert(key.to_owned());
        Some(o)
    }

    fn error(&self, decl: &Decl, what: &str) -> ToolError {
        ToolError::new(format!(
            "{}.{} ({}) {what}",
            self.pkg.path, decl.name, decl.file
        ))
    }

    fn claim(names: &mut BTreeMap<String, String>, rust: &str, go: &str, pkg: &str) -> Result<()> {
        if let Some(other) = names.insert(rust.to_owned(), go.to_owned()) {
            return Err(ToolError::new(format!(
                "{pkg}: {go} and {other} both become Rust {rust}; give one a rust_name override"
            )));
        }
        Ok(())
    }

    fn claim_type(&mut self, rust: &str, go: &str) -> Result<()> {
        Self::claim(&mut self.type_names, rust, go, &self.pkg.path)
    }

    fn claim_value(&mut self, rust: &str, go: &str) -> Result<()> {
        Self::claim(&mut self.value_names, rust, go, &self.pkg.path)
    }

    /// The rendered Go doc, or the (Markdown, one-line) fallback when Go has none.
    fn doc(text: &str, indent: usize, fallback: &str) -> Vec<String> {
        let lines = docs::render(text, indent);
        if lines.is_empty() {
            vec![format!("{}/// {fallback}", " ".repeat(indent))]
        } else {
            lines
        }
    }

    fn struct_item(&mut self, decl: &Decl, info: &TypeInfo) -> Result<Vec<String>> {
        let mut out = Self::doc(
            &docs::join(&[&decl.doc, &decl.comment]),
            0,
            &format!("Go type `{}`.", info.go_name),
        );
        out.extend(doc_alias(&info.rust_name, &decl.name));
        let mut derives = vec!["Clone"];
        if info.copy {
            derives.push("Copy");
        }
        derives.extend(["Debug", "Default", "PartialEq"]);
        if info.eq {
            derives.push("Eq");
        }
        derives.push("GoJson");
        out.push(format!("#[derive({})]", derives.join(", ")));
        out.extend(attribute(
            0,
            &[format!("go_type = {}", literal(&info.go_name))],
        ));
        let mut body = Vec::new();
        let mut field_names = BTreeMap::new();
        for f in &decl.fields {
            let key = format!("{}.{}", decl.name, f.name);
            let o = self.take(&key).cloned();
            if o.as_ref().is_some_and(|o| o.skip) {
                continue;
            }
            if !f.exported {
                return Err(self.error(
                    decl,
                    &format!("has unexported field {}; override it with skip", f.name),
                ));
            }
            let name = o
                .as_ref()
                .and_then(|o| o.rust_name.clone())
                .unwrap_or_else(|| self.field_name(f));
            if !names::is_ident(&name) {
                return Err(self.error(
                    decl,
                    &format!(
                        "field {} has no usable Rust name; give it a rust_name",
                        f.name
                    ),
                ));
            }
            if let Some(other) = field_names.insert(name.clone(), f.name.clone()) {
                return Err(self.error(
                    decl,
                    &format!(
                        "fields {other} and {} both become {name}; give one a rust_name",
                        f.name
                    ),
                ));
            }
            let ty = if let Some(ty) = o.as_ref().and_then(|o| o.rust_type.clone()) {
                for u in o.iter().flat_map(|o| &o.uses) {
                    let _ = self.ctx.uses.insert(u.clone());
                }
                ty
            } else {
                let inline = o.as_ref().is_some_and(|o| o.inline);
                self.reg.render(&f.ty, inline, &mut self.ctx)?
            };
            body.extend(Self::doc(
                &docs::join(&[&f.doc, &f.comment]),
                4,
                &format!("Go field `{}`.", f.name),
            ));
            let mut args = vec![format!("go = {}", literal(&f.name))];
            if let Some(tag) = &f.json {
                args.push(format!("json = {}", literal(tag)));
            }
            if f.embedded {
                args.push("embedded".to_owned());
            }
            body.extend(attribute(4, &args));
            body.extend(field_line(&names::escape(&name), &ty));
        }
        if body.is_empty() {
            out.push(format!("pub struct {};", info.rust_name));
        } else {
            out.push(format!("pub struct {} {{", info.rust_name));
            out.extend(body);
            out.push("}".to_owned());
        }
        Ok(out)
    }

    fn field_name(&self, f: &Field) -> String {
        let from_go = || names::snake(&f.name);
        match self.pc.field_names {
            FieldNames::Json => names::json_key(f.json.as_deref())
                .map(names::snake_from_json)
                .filter(|n| names::is_ident(n))
                .unwrap_or_else(from_go),
            FieldNames::Go => from_go(),
        }
    }

    fn named_item(&mut self, decl: &Decl, info: &TypeInfo) -> Result<Vec<String>> {
        let under = decl
            .ty
            .as_ref()
            .ok_or_else(|| self.error(decl, "has no underlying type"))?;
        let inner = self.reg.render(under, false, &mut self.ctx)?;
        let basic = under.kind == TypeKind::Basic;
        let mut derives = vec!["Clone"];
        if info.copy {
            derives.push("Copy");
        }
        derives.extend(["Debug", "Default", "PartialEq"]);
        if info.eq {
            derives.push("Eq");
        }
        if basic {
            derives.push("PartialOrd");
            if info.eq {
                derives.extend(["Ord", "Hash"]);
            }
        }
        derives.push("GoJson");
        let mut args = vec![format!("go_type = {}", literal(&info.go_name))];
        if basic && (under.name == "string" || is_integer(&under.name)) {
            args.push("map_key".to_owned());
        }
        let mut out = Self::doc(
            &docs::join(&[&decl.doc, &decl.comment]),
            0,
            &format!("Go type `{}`.", info.go_name),
        );
        out.extend(doc_alias(&info.rust_name, &decl.name));
        out.push(format!("#[derive({})]", derives.join(", ")));
        out.extend(attribute(0, &args));
        out.push(format!("pub struct {}(pub {inner});", info.rust_name));
        Ok(out)
    }

    fn alias_item(&mut self, decl: &Decl) -> Result<Vec<String>> {
        let target = decl
            .ty
            .as_ref()
            .filter(|t| t.kind == TypeKind::Named)
            .ok_or_else(|| self.error(decl, "aliases a type that is not a named type"))?;
        let info = self.reg.get(&target.pkg, &target.name).ok_or_else(|| {
            self.error(
                decl,
                &format!(
                    "aliases {}, which no typegen.json generates",
                    target.reflect
                ),
            )
        })?;
        let root = if info.crate_name == self.ctx.crate_name {
            "crate"
        } else {
            info.crate_name.as_str()
        };
        let alias = names::type_name(&decl.name);
        self.claim_type(&alias, &decl.name)?;
        let mut path = format!("{root}::{}::{}", info.module, info.rust_name);
        if alias != info.rust_name {
            path = format!("{path} as {alias}");
        }
        let mut out = Self::doc(
            &docs::join(&[&decl.doc, &decl.comment]),
            0,
            &format!(
                "Go alias `{}.{}` of `{}`.",
                self.pkg.name, decl.name, info.go_name
            ),
        );
        out.push(format!("pub use {path};"));
        Ok(out)
    }

    fn const_item(
        &mut self,
        decl: &Decl,
        o: Option<&Override>,
    ) -> Result<(Vec<String>, IndexConst)> {
        let declared = decl
            .ty
            .as_ref()
            .ok_or_else(|| self.error(decl, "has no type"))?;
        let go_type = o.and_then(|o| o.go_type.clone());
        let ty = if declared.kind == TypeKind::Basic && declared.name.starts_with("untyped ") {
            let go_type = go_type.ok_or_else(|| {
                self.error(
                    decl,
                    &format!(
                        "is an {} constant; give it an override with go_type",
                        declared.name
                    ),
                )
            })?;
            self.local_type(&go_type)
        } else if go_type.is_some() {
            return Err(self.error(
                decl,
                "is typed; go_type overrides are for untyped constants",
            ));
        } else {
            declared.clone()
        };
        let (rust_ty, ctor, _) = self.reg.const_type(&ty, &mut self.ctx)?;
        let string = decl.value_kind == "string";
        if string && ctor.is_some() {
            return Err(self.error(decl, "is a constant of a named string type (unsupported)"));
        }
        let value = const_literal(&decl.value, &decl.value_kind)
            .ok_or_else(|| self.error(decl, &format!("has unsupported value {}", decl.value)))?;
        let name = o
            .and_then(|o| o.rust_name.clone())
            .unwrap_or_else(|| names::screaming(&decl.name));
        if !names::is_ident(&name) {
            return Err(self.error(decl, "has no usable Rust name; give it a rust_name"));
        }
        self.claim_value(&name, &decl.name)?;
        let expr = ctor
            .as_ref()
            .map_or_else(|| value.clone(), |c| format!("{c}({value})"));
        let mut out = Self::doc(
            &docs::join(&[&decl.doc, &decl.comment]),
            0,
            &format!("Go constant `{}`.", decl.name),
        );
        out.extend(doc_alias(&name, &decl.name));
        let line = format!("pub const {name}: {rust_ty} = {expr};");
        if line.len() > WIDTH {
            out.push(format!("pub const {name}: {rust_ty} ="));
            out.push(format!("    {expr};"));
        } else {
            out.push(line);
        }
        let index = IndexConst {
            go_name: format!("{}.{}", self.pkg.name, decl.name),
            rust: format!("{}::{name}", self.pc.rust),
        };
        Ok((out, index))
    }

    /// A type named by an override: a basic type, or a type of this package.
    fn local_type(&self, name: &str) -> TypeRef {
        let basic = matches!(
            name,
            "bool"
                | "string"
                | "int"
                | "int8"
                | "int16"
                | "int32"
                | "int64"
                | "uint"
                | "uint8"
                | "uint16"
                | "uint32"
                | "uint64"
                | "float32"
                | "float64"
        );
        TypeRef {
            kind: if basic {
                TypeKind::Basic
            } else {
                TypeKind::Named
            },
            name: name.to_owned(),
            pkg: if basic {
                String::new()
            } else {
                self.pkg.path.clone()
            },
            pkg_name: if basic {
                String::new()
            } else {
                self.pkg.name.clone()
            },
            args: Vec::new(),
            elem: None,
            key: None,
            fields: Vec::new(),
            methods: Vec::new(),
            reflect: if basic {
                name.to_owned()
            } else {
                format!("{}.{name}", self.pkg.name)
            },
        }
    }
}

fn is_integer(name: &str) -> bool {
    matches!(
        name,
        "int"
            | "int8"
            | "int16"
            | "int32"
            | "int64"
            | "uint"
            | "uint8"
            | "uint16"
            | "uint32"
            | "uint64"
    )
}

/// A Rust string literal.
#[must_use]
pub fn literal(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            '\r' => out.push_str("\\r"),
            c if c.is_control() => out.extend(c.escape_unicode()),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// A constant's value as a Rust literal: integers with `_` every three digits from six digits
/// on (clippy's `unreadable_literal`), floats with a decimal point, strings quoted.
fn const_literal(value: &str, kind: &str) -> Option<String> {
    match kind {
        "int" => {
            let (sign, digits) = value.strip_prefix('-').map_or(("", value), |d| ("-", d));
            if digits.is_empty() || !digits.chars().all(|c| c.is_ascii_digit()) {
                return None;
            }
            if digits.len() < 6 {
                return Some(value.to_owned());
            }
            let mut grouped = String::new();
            for (i, c) in digits.chars().enumerate() {
                if i > 0 && (digits.len() - i) % 3 == 0 {
                    grouped.push('_');
                }
                grouped.push(c);
            }
            Some(format!("{sign}{grouped}"))
        }
        "float" => {
            if value.contains(['.', 'e']) {
                Some(value.to_owned())
            } else if value.chars().all(|c| c.is_ascii_digit() || c == '-') {
                Some(format!("{value}.0"))
            } else {
                None
            }
        }
        "bool" => Some(value.to_owned()),
        "string" => Some(literal(value)),
        _ => None,
    }
}

/// A `#[gojson(...)]` attribute, one argument per line when the arguments exceed rustfmt's
/// `attr_fn_like_width` or the line exceeds the width.
fn attribute(indent: usize, args: &[String]) -> Vec<String> {
    meta_list(indent, "gojson", args)
}

/// `#[doc(alias = "Go")]` for an item whose Rust name differs from its Go name
/// (`NoBidUnknownError` → `NO_BID_UNKNOWN_ERROR`), so that rustdoc search and grep find the
/// Rust item by the Go name a porter reads; nothing when the names are equal (rustc rejects an
/// alias equal to the item's name).
fn doc_alias(rust: &str, go: &str) -> Vec<String> {
    if rust == go {
        return Vec::new();
    }
    meta_list(0, "doc", &[format!("alias = {}", literal(go))])
}

/// `#[name(args)]`, one argument per line when the arguments exceed rustfmt's
/// `attr_fn_like_width` or the line exceeds the width.
fn meta_list(indent: usize, name: &str, args: &[String]) -> Vec<String> {
    let pad = " ".repeat(indent);
    let joined = args.join(", ");
    let line = format!("{pad}#[{name}({joined})]");
    if joined.len() <= ATTR_ARGS_WIDTH && line.len() <= WIDTH {
        return vec![line];
    }
    let mut out = vec![format!("{pad}#[{name}(")];
    let last = args.len().saturating_sub(1);
    for (i, arg) in args.iter().enumerate() {
        let comma = if i == last { "" } else { "," };
        out.push(format!("{pad}    {arg}{comma}"));
    }
    out.push(format!("{pad})]"));
    out
}

/// A struct field, with the type on its own line when the field exceeds the width.
fn field_line(name: &str, ty: &str) -> Vec<String> {
    let line = format!("    pub {name}: {ty},");
    if line.len() <= WIDTH {
        vec![line]
    } else {
        vec![format!("    pub {name}:"), format!("        {ty},")]
    }
}

/// `use` declarations for the paths, grouped and merged as rustfmt does with
/// `group_imports = "StdExternalCrate"` and `imports_granularity = "Crate"`.
#[must_use]
pub fn imports(paths: &BTreeSet<String>) -> Vec<String> {
    let mut groups: [BTreeMap<String, Tree>; 3] = Default::default();
    for path in paths {
        let mut segments = path.split("::");
        let Some(root) = segments.next() else {
            continue;
        };
        let group = match root {
            "std" | "core" | "alloc" => 0,
            "crate" | "super" | "self" => 2,
            _ => 1,
        };
        if let Some(g) = groups.get_mut(group) {
            g.entry(root.to_owned()).or_default().insert(segments);
        }
    }
    let mut out = Vec::new();
    for group in groups {
        if group.is_empty() {
            continue;
        }
        if !out.is_empty() {
            out.push(String::new());
        }
        let mut roots: Vec<(String, Tree)> = group.into_iter().collect();
        roots.sort_by(|a, b| root_order(&a.0, &b.0));
        for (root, tree) in roots {
            out.extend(use_lines(&root, &tree));
        }
    }
    out
}

/// One `use` declaration, its list wrapped as rustfmt wraps one that does not fit in the width:
/// one item per line around nested lists, otherwise as many as fit in the indented width less
/// the trailing comma.
fn use_lines(root: &str, tree: &Tree) -> Vec<String> {
    let line = format!("use {root}::{};", tree.render());
    let parts = tree.parts();
    if line.len() <= WIDTH || parts.len() < 2 {
        return vec![line];
    }
    let budget = WIDTH - 5;
    let mut out = vec![format!("use {root}::{{")];
    let mut current = String::new();
    let mut prev_nested = false;
    for part in parts {
        let nested = part.contains("::");
        if !current.is_empty()
            && (current.len() + 1 + part.len() + 1 > budget || nested || prev_nested)
        {
            out.push(format!("    {current}"));
            current.clear();
        }
        if !current.is_empty() {
            current.push(' ');
        }
        current.push_str(&part);
        current.push(',');
        prev_nested = nested;
    }
    out.push(format!("    {current}"));
    out.push("};".to_owned());
    out
}

fn root_order(a: &str, b: &str) -> Ordering {
    let rank = |s: &str| match s {
        "self" => 0,
        "super" => 1,
        "crate" => 2,
        _ => 3,
    };
    rank(a).cmp(&rank(b)).then_with(|| version_cmp(a, b))
}

/// rustfmt's version sort for import names: `_` before digits before upper case before lower
/// case, digit runs compared by value.
#[must_use]
pub fn version_cmp(left: &str, right: &str) -> Ordering {
    let rank = |ch: char| -> (u8, char) {
        match ch {
            '_' => (0, ch),
            '0'..='9' => (1, ch),
            'A'..='Z' => (2, ch),
            _ => (3, ch),
        }
    };
    let (mut lhs, mut rhs) = (left.chars().peekable(), right.chars().peekable());
    loop {
        match (lhs.peek().copied(), rhs.peek().copied()) {
            (None, None) => return Ordering::Equal,
            (None, Some(_)) => return Ordering::Less,
            (Some(_), None) => return Ordering::Greater,
            (Some(l), Some(r)) if l.is_ascii_digit() && r.is_ascii_digit() => {
                let (l_digits, r_digits) = (digit_run(&mut lhs), digit_run(&mut rhs));
                let l_value = l_digits.trim_start_matches('0');
                let r_value = r_digits.trim_start_matches('0');
                let ord = l_value
                    .len()
                    .cmp(&r_value.len())
                    .then_with(|| l_value.cmp(r_value))
                    .then_with(|| l_digits.len().cmp(&r_digits.len()));
                if ord != Ordering::Equal {
                    return ord;
                }
            }
            (Some(l), Some(r)) => {
                let ord = rank(l).cmp(&rank(r));
                if ord != Ordering::Equal {
                    return ord;
                }
                let _ = lhs.next();
                let _ = rhs.next();
            }
        }
    }
}

/// The run of ASCII digits at the iterator's position.
fn digit_run(it: &mut Peekable<Chars<'_>>) -> String {
    let mut s = String::new();
    while let Some(c) = it.next_if(char::is_ascii_digit) {
        s.push(c);
    }
    s
}

/// A use tree: the paths below one prefix.
#[derive(Debug, Default)]
struct Tree {
    leaf: bool,
    children: BTreeMap<String, Self>,
}

impl Tree {
    fn insert<'a, I: Iterator<Item = &'a str>>(&mut self, mut segments: I) {
        match segments.next() {
            None => self.leaf = true,
            Some(s) => self
                .children
                .entry(s.to_owned())
                .or_default()
                .insert(segments),
        }
    }

    /// The tree below its prefix: `a`, `a::b`, or `{a, b::c}`.
    fn render(&self) -> String {
        let parts = self.parts();
        if parts.len() == 1 && !self.leaf {
            return parts.into_iter().next().unwrap_or_default();
        }
        format!("{{{}}}", parts.join(", "))
    }

    /// The rendered items of the tree's list, in rustfmt's order.
    fn parts(&self) -> Vec<String> {
        let mut parts: Vec<(String, String)> = Vec::new();
        if self.leaf {
            parts.push(("self".to_owned(), "self".to_owned()));
        }
        for (name, child) in &self.children {
            let text = if child.children.is_empty() {
                name.clone()
            } else {
                format!("{name}::{}", child.render())
            };
            parts.push((name.clone(), text));
        }
        parts.sort_by(|a, b| match (a.0.as_str(), b.0.as_str()) {
            ("self", "self") => Ordering::Equal,
            ("self", _) => Ordering::Less,
            (_, "self") => Ordering::Greater,
            (x, y) => version_cmp(x, y),
        });
        parts.into_iter().map(|p| p.1).collect()
    }
}

#[cfg(test)]
mod tests {
    use std::{cmp::Ordering, collections::BTreeSet};

    use super::{attribute, const_literal, doc_alias, imports, literal, version_cmp};
    use crate::{error::Result, testutil::check_eq};

    #[test]
    fn sorts_and_groups_imports_like_rustfmt() -> Result<()> {
        let paths: BTreeSet<String> = [
            "crate::native1::request",
            "crate::adcom1",
            "pbs_gojson::RawJson",
            "pbs_gojson::GoJson",
            "std::collections::BTreeMap",
            "super::Video",
        ]
        .into_iter()
        .map(str::to_owned)
        .collect();
        check_eq(
            &imports(&paths),
            &[
                "use std::collections::BTreeMap;",
                "",
                "use pbs_gojson::{GoJson, RawJson};",
                "",
                "use super::Video;",
                "use crate::{adcom1, native1::request};",
            ]
            .map(str::to_owned)
            .to_vec(),
            "imports",
        )?;
        // A list longer than the width wraps as rustfmt wraps it.
        let long: BTreeSet<String> = [
            "BidType",
            "BidderName",
            "CookieStatus",
            "ExtDeviceInt",
            "ExtImpAdUnitCodePrebid",
            "ExtImpAppnexusKeywords",
            "ImpExtAdnunitusTargeting",
            "ImpExtRubiconDebug",
            "PriceGranularity",
            "RubiconVideoParams",
            "StringOrStringArray",
            "UserSyncType",
        ]
        .into_iter()
        .map(|name| format!("super::{name}"))
        .collect();
        check_eq(
            &imports(&long),
            &[
                "use super::{",
                "    BidType, BidderName, CookieStatus, ExtDeviceInt, ExtImpAdUnitCodePrebid,",
                "    ExtImpAppnexusKeywords, ImpExtAdnunitusTargeting, ImpExtRubiconDebug, \
                 PriceGranularity,",
                "    RubiconVideoParams, StringOrStringArray, UserSyncType,",
                "};",
            ]
            .map(str::to_owned)
            .to_vec(),
            "wrapped imports",
        )?;
        let mut names = vec![
            "b", "A", "a", "B", "c1", "c10", "c2", "Ab", "AB", "aB", "a_b", "a1",
        ];
        names.sort_by(|a, b| version_cmp(a, b));
        check_eq(
            &names,
            &vec![
                "A", "AB", "Ab", "B", "a", "a_b", "a1", "aB", "b", "c1", "c2", "c10",
            ],
            "version sort",
        )?;
        check_eq(
            &version_cmp("a01", "a1"),
            &Ordering::Greater,
            "leading zeros",
        )
    }

    #[test]
    fn formats_literals_and_attributes() -> Result<()> {
        check_eq(
            &const_literal("-2", "int").as_deref(),
            &Some("-2"),
            "negative",
        )?;
        check_eq(
            &const_literal("1000000", "int").as_deref(),
            &Some("1_000_000"),
            "grouped",
        )?;
        check_eq(
            &const_literal("12345", "int").as_deref(),
            &Some("12345"),
            "short",
        )?;
        check_eq(
            &const_literal("3", "float").as_deref(),
            &Some("3.0"),
            "float",
        )?;
        check_eq(&const_literal("x", "int"), &None, "bad int")?;
        check_eq(literal("a\"b\\").as_str(), "\"a\\\"b\\\\\"", "escapes")?;
        check_eq(
            &attribute(4, &["go = \"ID\"".to_owned()]),
            &vec!["    #[gojson(go = \"ID\")]".to_owned()],
            "short attribute",
        )?;
        let long = [
            "go = \"AVeryLongGoFieldNameThatGoesOnAndOn\"".to_owned(),
            format!("json = \"{}\"", "x".repeat(50)),
        ];
        check_eq(
            &attribute(4, &long),
            &vec![
                "    #[gojson(".to_owned(),
                "        go = \"AVeryLongGoFieldNameThatGoesOnAndOn\",".to_owned(),
                format!("        json = \"{}\"", "x".repeat(50)),
                "    )]".to_owned(),
            ],
            "long attribute",
        )
    }

    #[test]
    fn aliases_items_renamed_from_go() -> Result<()> {
        check_eq(
            &doc_alias("NO_BID_UNKNOWN_ERROR", "NoBidUnknownError"),
            &vec!["#[doc(alias = \"NoBidUnknownError\")]".to_owned()],
            "renamed",
        )?;
        check_eq(
            &doc_alias("APIVPAID10", "APIVPAID10"),
            &Vec::<String>::new(),
            "same name",
        )
    }
}
