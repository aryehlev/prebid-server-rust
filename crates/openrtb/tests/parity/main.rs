//! Parity of `pbs_openrtb` with `github.com/prebid/openrtb/v20` v20.3.0 as prebid-server uses it.
//!
//! * `golden` replays, byte for byte, the differential goldens that `testdata/go` writes with the
//!   Go types: every `OpenRTB` document of prebid-server's test corpora (adapter fixtures, exchange
//!   tests, endpoint sample requests, first-party data tests and the native markup they carry), the
//!   openrtb module's testdata, generated mutations of every ported type, and adversarial documents
//!   (merges on duplicate keys, slice elements, Unicode key folding, malformed objects, nested
//!   paths, the nesting limit), each decoded with `jsonutil.Unmarshal` and `json.Unmarshal` and
//!   re-encoded with `jsonutil.Marshal`, `json.Marshal` and an `Encoder` without HTML escaping.
//! * `encode` replays the encodings of values no document decodes to (NaN, infinities, invalid
//!   `json.RawMessage` bytes).
//! * `module` ports the openrtb module's own marshaling tests.
//! * `inventory` checks every Go type, field, JSON tag and constant against the metadata of the Go
//!   build in `testdata/go_struct_meta.json`.
//! * `functions` tests the hand-written ports of the Go functions and methods.
//! * `shapes` checks the serde code (serde derives and `MergeClone`) of every ported type against
//!   the shapes `testdata/go` writes: each field's samples, zero value, null and integer extremes
//!   decoded and written back as `jsonutil` and as `encoding/json` do, and merges of samples, null
//!   and values of the wrong JSON type; every difference from Go must fall in a ledger entry.
//! * `serde_goldens` replays the goldens of `golden` through the serde code: every difference from
//!   Go must fall in a ledger entry, and prebid-server's own documents may differ only in spelling
//!   and in the key case of the fixtures it lists.
//!
//! `index` is generated by `pbs-devtools typegen`. Regenerate the goldens with
//! `GOTOOLCHAIN=go1.26.2 go run .` in `crates/openrtb/testdata/go`; the corpora are read from
//! the Go root (`$PBS_GO_ROOT`, else `.upstream`, which `scripts/fetch-upstream.sh` makes).

