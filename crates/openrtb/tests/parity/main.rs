//! Parity of `pbs_openrtb` with `github.com/prebid/openrtb/v20` v20.3.0 as prebid-server uses it.
//!
//! * `golden` replays, byte for byte, the differential goldens that `testdata/go` writes with the
//!   Go types: every `OpenRTB` document of prebid-server's test corpora (adapter fixtures, exchange
//!   tests, endpoint sample requests and the native markup they carry), the openrtb module's
//!   testdata, and generated mutations of every ported type, each decoded with `jsonutil.Unmarshal`
//!   and `json.Unmarshal` and re-encoded with `jsonutil.Marshal`, `json.Marshal` and an `Encoder`
//!   without HTML escaping.
//! * `module` ports the openrtb module's own marshaling tests.
//! * `inventory` checks every Go type, field, JSON tag and constant against the metadata of the Go
//!   build in `rust/testdata/go_struct_meta.json`.
//! * `functions` tests the hand-written ports of the Go functions and methods.
//!
//! `index` is generated by `pbs-devtools typegen`. Regenerate the goldens from the repository
//! root with `GOTOOLCHAIN=go1.26.2 go run ./rust/crates/openrtb/testdata/go`.

